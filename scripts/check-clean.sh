#!/usr/bin/env bash
# Garde-fou exécuté par le hook pre-push et par la CI.
#
# Vérifie que ni les messages de commit de la branche, ni le contenu du
# dépôt ne contiennent de mention d'outils de génération de code, et
# qu'aucun fichier de configuration propre à ces outils n'a été versionné.
#
# Usage : scripts/check-clean.sh [ref-de-base]   (défaut : origin/main)
set -Eeuo pipefail

base_ref="${1:-${CHECK_CLEAN_BASE:-origin/main}}"
status=0

red=''
green=''
reset=''
if [[ -t 1 ]]; then
  red=$'\033[31m'
  green=$'\033[32m'
  reset=$'\033[0m'
fi

fail() {
  printf '%sSTOP%s %s\n' "$red" "$reset" "$1" >&2
  status=1
}

cd "$(git rev-parse --show-toplevel)"

# 1. Messages de commit propres à la branche.
commit_pattern='co-authored|generated with|claude|anthropic|openai|gpt|copilot|\bAI\b|\bIA\b|llm'
if git rev-parse --verify --quiet "${base_ref}^{commit}" >/dev/null; then
  if git log --format='%B' "${base_ref}..HEAD" | grep -Eiq "$commit_pattern"; then
    fail "un message de commit entre ${base_ref} et HEAD contient un motif interdit :"
    git log --format='%h %s' "${base_ref}..HEAD" |
      while read -r sha _; do
        if git log -1 --format='%B' "$sha" | grep -Eiq "$commit_pattern"; then
          printf '  - %s\n' "$(git log -1 --format='%h %s' "$sha")" >&2
        fi
      done
  fi
else
  # Sans référence de base (clone superficiel, premier push), on ne peut
  # pas isoler les commits de la branche : on contrôle au moins HEAD.
  printf 'Référence %s introuvable : contrôle limité au dernier commit.\n' "$base_ref" >&2
  if git log -1 --format='%B' HEAD | grep -Eiq "$commit_pattern"; then
    fail "le dernier commit contient un motif interdit."
  fi
fi

# 2. Contenu versionné. Ce script est exclu puisqu'il porte les motifs.
content_pattern='claude|anthropic|openai|chatgpt|copilot|generated by'
if matches="$(git grep -Eil "$content_pattern" -- . ':!pnpm-lock.yaml' ':!scripts/check-clean.sh')"; then
  fail "motif interdit trouvé dans les fichiers suivants :"
  while IFS= read -r file; do printf '  - %s\n' "$file" >&2; done <<<"$matches"
fi

# 3. Fichiers de configuration d'outils qui n'ont rien à faire ici.
forbidden_files="$(git ls-files | grep -Ei '(^|/)(CLAUDE\.md|AGENTS\.md|PROMPT\.md|\.cursor(rules)?(/|$)|\.aider|\.continue/|\.github/copilot-)' || true)"
if [[ -n "$forbidden_files" ]]; then
  fail "fichiers interdits versionnés :"
  while IFS= read -r file; do printf '  - %s\n' "$file" >&2; done <<<"$forbidden_files"
fi

if [[ "$status" -eq 0 ]]; then
  printf '%sOK%s dépôt propre.\n' "$green" "$reset"
fi
exit "$status"
