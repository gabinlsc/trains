export function rollingStockById(id: string): RollingStock | undefined {
  return ROLLING_STOCK.find((stock) => stock.id === id);
}

/** Vrai si ce matériel peut circuler sous cette électrification (ou sans). */
export function acceptsPower(stock: RollingStock, electrification: Electrification): boolean {
  if (stock.traction !== 'electric') return true;
  return electrification !== 'none' && stock.voltages.includes(electrification);
}
