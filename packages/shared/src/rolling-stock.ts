import { z } from 'zod';
import { ElectrificationSchema, GaugeSchema, type Electrification } from './infrastructure.ts';

/**
 * Catalogue du matériel roulant. Les modèles sont génériques : ils
 * reprennent les caractéristiques typiques des familles de trains en
 * service en France, sans désigner un constructeur. Les identifiants sont
 * persistés dans les sauvegardes : ne jamais en renommer un.
 */

export const RollingStockCategorySchema = z.enum([
  'grande-vitesse',
  'intercites',
  'regional',
  'periurbain',
  'fret',
]);
export type RollingStockCategory = z.infer<typeof RollingStockCategorySchema>;

/** électrique, thermique, ou bimode (électrique sous caténaire, thermique ailleurs). */
export const TractionSchema = z.enum(['electric', 'diesel', 'bimode']);
export type Traction = z.infer<typeof TractionSchema>;

export const RollingStockSchema = z.object({
  id: z.string().regex(/^[a-z0-9-]+$/),
  name: z.string(),
  category: RollingStockCategorySchema,
  traction: TractionSchema,
  /** Tensions acceptées en traction électrique (vide pour un thermique). */
  voltages: z.array(ElectrificationSchema.exclude(['none'])),
  gauge: GaugeSchema,
  maxSpeedKmh: z.number().int().positive(),
  /** Places assises, et capacité totale debout comprise. */
  seats: z.number().int().nonnegative(),
  capacity: z.number().int().nonnegative(),
  /** Charge utile d'un train de fret (t), 0 pour les voyageurs. */
  payloadT: z.number().nonnegative(),
  lengthM: z.number().positive(),
  massT: z.number().positive(),
  powerKw: z.number().positive(),
  /** Accélération au démarrage et décélération de service (m/s²). */
  accelerationMs2: z.number().positive(),
  decelerationMs2: z.number().positive(),
  /** Prix d'achat d'une rame (M€) et coût d'exploitation (€ par train-km). */
  priceM: z.number().positive(),
  costPerTrainKm: z.number().positive(),
  /** Exige l'ERTMS niveau 2 au-delà de 220 km/h (signalisation en cabine). */
  cabSignalling: z.boolean(),
});
export type RollingStock = z.infer<typeof RollingStockSchema>;

